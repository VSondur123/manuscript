#!/usr/bin/env python3
"""Migrate a legacy ManuScript project (state.json at the project root) to the .ms/ layout, in place.

Usage: migrate_project.py PROJECT_ID [--root DIR]
Steps: tar.gz backup of the whole project folder (kept in <root>/manuscript/) -> move internals into .ms/
-> draft.md becomes <id>-report.md with figure links rewritten to .ms/figures/... -> figure-spec CSV paths
rewritten -> state paths updated (stage, plan approval and history are preserved) -> figures rebuilt and state synced.
Nothing is deleted. The Markdown approval (if any) is kept only if the report text is unchanged.
"""
import argparse
import os
import re
import shutil
import subprocess
import sys
import tarfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ms_common as C  # noqa: E402
import ms_state as S  # noqa: E402

MOVES = [("state.json", "state.json"), ("project-config.yaml", "project-config.yaml"),
         ("evidence-inventory.md", "evidence-inventory.md"), ("references.bib", "references.bib"),
         ("approved", "approved"), (".history", "history"), ("latex", "latex"), ("logs", "logs"),
         ("validation", "validation"), ("figures", "figures"), ("figures-src", "figures-src"), ("data", "data"),
         ("assets", "assets")]


def migrate(root, pid):
    d = S.pdir(root, pid)
    w = os.path.join(d, S.WORK)
    if not os.path.isfile(os.path.join(d, "state.json")):
        raise S.StateError("%s has no legacy state.json" % d)
    if os.path.exists(os.path.join(w, "state.json")):
        raise S.StateError("already migrated (.ms/state.json exists)")
    stamp = C.now().replace(":", "").replace("-", "")
    backup = os.path.join(S.projects_dir(root), ".premigration-%s-%s.tar.gz" % (pid, stamp))
    with tarfile.open(backup, "w:gz") as t:
        t.add(d, arcname=pid)
    os.makedirs(w, exist_ok=True)
    moved = []
    for src, dst in MOVES:
        if os.path.exists(os.path.join(d, src)):
            shutil.move(os.path.join(d, src), os.path.join(w, dst))
            moved.append(src)
    report = os.path.join(d, "%s-report.md" % pid)
    old_draft = os.path.join(d, "draft.md")
    if os.path.isfile(old_draft):
        if os.path.exists(report):
            raise S.StateError("%s already exists; refusing to overwrite" % report)
        text = C.read_text(old_draft)
        text = re.sub(r"(!\[[^\]]*\]\()figures/", r"\1%s/figures/" % S.WORK, text)
        with open(report, "w", encoding="utf-8") as f:
            f.write(text)
        shutil.copy2(old_draft, os.path.join(w, "history", "draft.md.premigration"))
        os.remove(old_draft)
    # figure specs: csv paths were relative to the project dir (data/x.csv) -> now .ms/data/x.csv
    sd = os.path.join(w, "figures-src")
    if os.path.isdir(sd):
        for fn in os.listdir(sd):
            if fn.endswith(".json"):
                p = os.path.join(sd, fn)
                s = C.read_text(p)
                s2 = re.sub(r'("csv"\s*:\s*")(?!\.ms/)(data/)', r"\1%s/\2" % S.WORK, s)
                if s2 != s:
                    with open(p, "w", encoding="utf-8") as f:
                        f.write(s2)
    mp = os.path.join(w, "figures", "manifest.json")
    if os.path.isfile(mp):
        os.remove(mp)  # regenerated by build_figures.py with .ms/-relative paths
    st = C.read_json(os.path.join(w, "state.json"))
    for key, rec in st["artifacts"].items():
        rec["path"] = S.ARTIFACTS[key].format(pid=pid)
    st["markdown_approval"] = st.get("markdown_approval")  # kept; verify() reports it stale if the report changed
    st["history"].append({"at": C.now(), "from": st["stage"], "to": st["stage"], "note": "migrated to .ms/ layout; backup " + os.path.basename(backup)})
    S.save(root, pid, st)
    return backup, moved


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("project"); ap.add_argument("--root", default=os.getcwd())
    a = ap.parse_args(argv)
    root = os.path.abspath(a.root)
    try:
        backup, moved = migrate(root, a.project)
    except (S.StateError, OSError) as e:
        print("ERROR: %s" % e, file=sys.stderr)
        return 2
    print("Backup: %s" % backup)
    print("Moved into %s/: %s" % (S.WORK, ", ".join(moved)))
    here = os.path.dirname(os.path.abspath(__file__))
    runs = [[sys.executable, os.path.join(here, "build_figures.py"), "--root", root, "--project", a.project],
            [sys.executable, os.path.join(here, "ms_state.py"), "--root", root, "sync", a.project]]
    for cmd in runs:
        r = subprocess.run(cmd, capture_output=True, text=True)
        print((r.stdout + r.stderr).strip())
    return 0


if __name__ == "__main__":
    sys.exit(main())
