#!/usr/bin/env python3
"""Convert the APPROVED Markdown snapshot of a project to LaTeX with pandoc.

Refuses to run unless the Markdown approval is current (draft hash == approved hash) and the
approved snapshot is intact. Never reads the working draft as input.

Usage: md_to_latex.py [--project ID] [--root DIR] [--template-file FILE.latex]
Output: <project>/.ms/latex/<id>.tex (+ references.bib and figures copied next to it)
Allowed mechanical changes (logged): a trailing empty 'References' heading is dropped because
BibTeX prints the bibliography; "[Figure](#fig-x)" links become "Figure~\\ref{fig-x}".
"""
import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ms_common as C  # noqa: E402
import ms_state as S  # noqa: E402

SKILL_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REF_WORDS = r"Figure|Fig\.|Table|Tab\.|Equation|Eq\.|Section|Sec\.|Appendix|Chapter|Listing"


def prepare_markdown(text):
    """Return (text_for_pandoc, [log lines])."""
    log = []
    gen = re.sub(r"(?:\n#{1,2}[ \t]+(?:References|Bibliography)[ \t]*\n+)?<!-- references:start -->.*?<!-- references:end -->\n*", "\n", text, flags=re.S)
    if gen != text:
        log.append("dropped generated review reference list (bibliography is generated by BibTeX)")
        text = gen
    stripped = re.sub(r"\n#{1,2}\s+(References|Bibliography)\s*\n*\Z", "\n", text)
    if stripped != text:
        log.append("dropped trailing empty References heading (bibliography is generated by BibTeX)")
    return stripped, log


def doctype_args(dt):
    """Extra pandoc args from a doctype: custom pandoc template and Lua filters (paths relative to the skill)."""
    args = []
    if dt.get("pandoc_template"):
        args += ["--template", os.path.join(SKILL_DIR, dt["pandoc_template"])]
    for f in dt.get("lua_filters") or []:
        args += ["--lua-filter", os.path.join(SKILL_DIR, f)]
    return args


def postprocess(tex, dt=None):
    tex2, n = re.subn(r"\\hyperref\[([^\]]+)\]\{(%s)\}" % REF_WORDS, r"\2~\\ref{\1}", tex)
    if dt and dt.get("cite_command"):  # e.g. IEEEtran uses the 'cite' package, not natbib
        tex2 = re.sub(r"\\cite[pt]\*?(?=[\[{])", "\\\\" + dt["cite_command"], tex2)
    if dt and dt.get("fig_abbrev"):  # IEEE style: "Fig. 1"
        tex2 = tex2.replace("Figure~\\ref", "Fig.~\\ref")
    tex2 = re.sub(r"\\bibliography\{([^}]*)\}",
                  lambda m: "\\bibliography{%s}" % ",".join(re.sub(r"\.bib$", "", b.strip()) for b in m.group(1).split(",")), tex2)
    return tex2, n


def strip_work(rel):
    """Draft image links point into the hidden .ms/ folder; inside the LaTeX build dir they are plain figures/..."""
    return rel[len(S.WORK) + 1:] if rel.startswith(S.WORK + "/") else rel


def localize_images(text):
    return re.sub(r"(!\[[^\]]*\]\()" + re.escape(S.WORK) + r"/", r"\1", text)


def preview(root, pid, st, template_file=None):
    """Draft preview: unapproved, marked on every page, never recorded in state, never used for delivery."""
    d = S.pdir(root, pid)
    if not C.which("pandoc"):
        raise S.StateError("pandoc not installed (brew install pandoc)")
    draft = S.artifact_path(root, pid, "draft")
    if not os.path.isfile(draft):
        raise S.StateError("%s-report.md does not exist yet" % pid)
    dt_path = os.path.join(SKILL_DIR, "doctypes", "%s.yaml" % st["doctype"])
    dt = C.load_yaml(dt_path) if os.path.isfile(dt_path) else {}
    defaults = os.path.join(SKILL_DIR, dt.get("latex_defaults", "templates/latex/article.yaml"))
    latex_dir = os.path.join(d, S.WORK, "latex")
    os.makedirs(latex_dir, exist_ok=True)
    text, log = prepare_markdown(C.read_text(draft))
    for m in re.finditer(r"!\[[^\]]*\]\(([^)\s]+)", text):
        rel = m.group(1)
        src = os.path.normpath(os.path.join(d, rel))
        if not re.match(r"^[a-z]+://", rel) and os.path.isfile(src):
            dst = os.path.join(latex_dir, strip_work(rel))
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(src, dst)
    text = localize_images(text)
    mark = (r"\\usepackage{fancyhdr}\\pagestyle{fancy}\\fancyhf{}"
            r"\\fancyhead[C]{\\textbf{DRAFT PREVIEW -- NOT APPROVED}}\\fancyfoot[C]{\\thepage}")
    cmd = ["pandoc", "-f", "markdown", "-t", "latex", "--defaults", defaults, "-V", "header-includes=" + mark.replace("\\\\", "\\")]
    bib = S.artifact_path(root, pid, "bibliography")
    if os.path.isfile(bib) and "@" in C.read_text(bib):
        shutil.copy2(bib, os.path.join(latex_dir, "references.bib"))
        cmd += ["--natbib", "--bibliography", "references.bib"]
    cmd += doctype_args(dt)
    if template_file:
        cmd += ["--template", os.path.abspath(template_file)]
    name = "%s-preview.tex" % pid
    with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False, dir=latex_dir, encoding="utf-8") as tf:
        tf.write(text)
        tmp = tf.name
    try:
        r = subprocess.run(cmd + ["-o", name, tmp], cwd=latex_dir, capture_output=True, text=True)
    finally:
        os.unlink(tmp)
    if r.returncode != 0:
        raise S.StateError("pandoc failed:\n%s" % r.stderr)
    tex_path = os.path.join(latex_dir, name)
    tex, _ = postprocess(C.read_text(tex_path), dt)
    with open(tex_path, "w", encoding="utf-8") as f:
        f.write("%% DRAFT PREVIEW generated %s from UNAPPROVED report. Not a deliverable.\n" % C.now() + tex)
    print("Wrote %s (DRAFT PREVIEW; state not changed)" % tex_path)
    print("Compile with: compile_latex.sh %s" % tex_path)
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--project"); ap.add_argument("--root", default=os.getcwd())
    ap.add_argument("--template-file", help="custom pandoc LaTeX template (overrides config 'template')")
    ap.add_argument("--preview", action="store_true",
                    help="convert the CURRENT unapproved draft to a DRAFT-marked <id>-preview.tex; no approval needed, state untouched")
    a = ap.parse_args(argv)
    root = os.path.abspath(a.root)
    try:
        pid = S.resolve(root, a.project)
        st = S.load(root, pid)
        d = S.pdir(root, pid)
        if a.preview:
            return preview(root, pid, st, a.template_file)
        if S.markdown_approval_status(root, pid, st) != "current":
            raise S.StateError("Markdown is not currently approved (never approved, or draft changed). Get 'APPROVE MARKDOWN' first.")
        drift = [c for c in S.verify(root, pid, st) if c["artifact"] == "approved"]
        if drift:
            raise S.StateError("Approved snapshot problem: %s" % drift[0]["detail"])
        if not C.which("pandoc"):
            raise S.StateError("pandoc not installed (brew install pandoc)")
        ap_rec = st["markdown_approval"]
        snap = os.path.join(d, ap_rec["snapshot"])
        cfg_path = S.artifact_path(root, pid, "config")
        cfg = C.load_yaml(cfg_path) if os.path.isfile(cfg_path) else {}
        dt_path = os.path.join(SKILL_DIR, "doctypes", "%s.yaml" % st["doctype"])
        dt = C.load_yaml(dt_path) if os.path.isfile(dt_path) else {}
        defaults = os.path.join(SKILL_DIR, dt.get("latex_defaults", "templates/latex/article.yaml"))
        custom_tpl = a.template_file or cfg.get("template")
        if cfg.get("citation_style") == "author-year" or dt.get("citation_style") == "author-year":
            pass  # natbib handles both; style comes from biblio-style variable
        latex_dir = os.path.join(d, S.WORK, "latex")
        os.makedirs(latex_dir, exist_ok=True)
        text, log = prepare_markdown(C.read_text(snap))
        # copy referenced local images next to the .tex (originals untouched)
        for m in re.finditer(r"!\[[^\]]*\]\(([^)\s]+)", text):
            src_rel = m.group(1)
            if re.match(r"^[a-z]+://", src_rel):
                continue
            src = os.path.normpath(os.path.join(d, src_rel))
            if not os.path.isfile(src):
                raise S.StateError("Figure file missing: %s" % src_rel)
            dst = os.path.join(latex_dir, strip_work(src_rel))
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(src, dst)
            log.append("copied figure %s" % src_rel)
        text = localize_images(text)
        bib = S.artifact_path(root, pid, "bibliography")
        cmd = ["pandoc", "-f", "markdown", "-t", "latex", "--defaults", defaults]
        if os.path.isfile(bib) and C.read_text(bib).strip() and "@" in C.read_text(bib):
            shutil.copy2(bib, os.path.join(latex_dir, "references.bib"))
            cmd += ["--natbib", "--bibliography", "references.bib"]
        cmd += doctype_args(dt)
        if custom_tpl:
            cmd += ["--template", os.path.abspath(os.path.join(root, custom_tpl))]
        out_name = "%s.tex" % pid
        with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False, dir=latex_dir, encoding="utf-8") as tf:
            tf.write(text)
            tmp = tf.name
        try:
            r = subprocess.run(cmd + ["-o", out_name, tmp], cwd=latex_dir, capture_output=True, text=True)
        finally:
            os.unlink(tmp)
        if r.returncode != 0:
            raise S.StateError("pandoc failed:\n%s" % r.stderr)
        tex_path = os.path.join(latex_dir, out_name)
        tex, n = postprocess(C.read_text(tex_path), dt)
        if n:
            log.append("converted %d cross-reference link(s) to \\ref" % n)
        header = "%% Generated by ManuScript from %s (sha256 %s). Edit the Markdown, not this file, unless you accept re-approval.\n" % (
            ap_rec["snapshot"], ap_rec["sha256"][:16])
        with open(tex_path, "w", encoding="utf-8") as f:
            f.write(header + tex)
        if r.stderr.strip():
            log.append("pandoc warnings: " + r.stderr.strip().replace("\n", " | "))
        with open(os.path.join(d, S.WORK, "logs", "latex-generation.log"), "w", encoding="utf-8") as f:
            f.write("\n".join(["generated_at: " + C.now(), "source: " + ap_rec["snapshot"], "command: " + " ".join(cmd)] + log) + "\n")
        st["latex"] = {"path": os.path.relpath(tex_path, d), "sha256": C.sha256_file(tex_path),
                       "version": st["latex"].get("version", 0) + 1, "from_approved_sha256": ap_rec["sha256"]}
        if st["stage"] == "MARKDOWN_APPROVED":
            S.set_stage(root, pid, st, "LATEX_GENERATION", "latex generated")
        S.save(root, pid, st)
        print("Wrote %s" % tex_path)
        for l in log:
            print(" - " + l)
        return 0
    except (S.StateError, OSError, ValueError) as e:
        print("ERROR: %s" % e, file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
